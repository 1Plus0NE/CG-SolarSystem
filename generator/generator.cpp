bool verifyMetric(const string& name, float value, float min) {
    if (value < min) {
        cerr << "Error: " << name << " must be at least " << min
             << " (got " << value << ")" << endl;
        return false;
    }
    return true;
}

// ============================================================================
// writeOutput — VertList version (proper parametric UVs from the generators)
// ============================================================================

void writeOutput(const VertList& verts, const string& file) {
    string outputPath = "../../figures/" + file;
    ofstream out(outputPath);
    if (!out.is_open()) {
        cerr << "Error: Could not open file " << outputPath << endl;
        cerr << "Make sure the 'figures' directory exists!" << endl;
        return;
    }

    out << "# Generated by CG-SolarSystem\n";
    out << fixed << setprecision(6);

    for (const auto& v : verts)
        out << "v "  << v.x  << ' ' << v.y  << ' ' << v.z  << '\n';
    for (const auto& v : verts)
        out << "vt " << v.u  << ' ' << v.v  << '\n';
    for (const auto& v : verts)
        out << "vn " << v.nx << ' ' << v.ny << ' ' << v.nz << '\n';

    int n = (int)verts.size();
    for (int i = 0; i + 2 < n; i += 3)
        out << "f "
            << i+1 << '/' << i+1 << '/' << i+1 << ' '
            << i+2 << '/' << i+2 << '/' << i+2 << ' '
            << i+3 << '/' << i+3 << '/' << i+3 << '\n';

    out.close();
    cout << "Figure generated successfully: " << outputPath << endl;
    cout << "Total: " << verts.size() << " vertices ("
         << verts.size() / 3 << " triangles)" << endl;
}

