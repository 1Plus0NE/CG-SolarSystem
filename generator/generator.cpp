// Scatter-specific writeOutput using the legacy planar-projection UV path
static void writeOutputLegacy(const list<string>& vertices, const string& file) {
    string outputPath = "../../figures/" + file;
    ofstream outFile(outputPath);
    if (!outFile.is_open()) {
        cerr << "Error: Could not open file " << outputPath << endl;
        return;
    }
    using Vec3 = array<float, 3>;
    using Vec2 = array<float, 2>;

    vector<Vec3> points;
    points.reserve(vertices.size());
    for (const auto& vertex : vertices) points.push_back(parseVec3(vertex));

    outFile << "# Generated by CG-SolarSystem\n";

    unordered_map<string, int> posToIndex;
    vector<Vec3> uniquePos;
    vector<Vec3> accumNormals;
    vector<Vec2> accumUV;
    vector<int> uvCount;

    auto makeKey = [](const Vec3& p) {
        ostringstream ss;
        ss << fixed << setprecision(6) << p[0] << "," << p[1] << "," << p[2];
        return ss.str();
    };

    for (size_t i = 0; i + 2 < points.size(); i += 3) {
        const Vec3& p0=points[i]; const Vec3& p1=points[i+1]; const Vec3& p2=points[i+2];
        Vec3 normal = crossVec(subtractVec(p1,p0), subtractVec(p2,p0));
        normalizeVec(normal);
        auto triUV = buildTriangleUVs(p0, p1, p2, normal);
        const Vec3 tp[3]={p0,p1,p2};
        for (int k=0;k<3;k++){
            string key=makeKey(tp[k]);
            int idx;
            auto it=posToIndex.find(key);
            if (it==posToIndex.end()){
                idx=(int)uniquePos.size(); posToIndex.emplace(key,idx);
                uniquePos.push_back(tp[k]); accumNormals.push_back({0,0,0});
                accumUV.push_back({0,0}); uvCount.push_back(0);
            } else idx=it->second;
            accumNormals[idx][0]+=normal[0]; accumNormals[idx][1]+=normal[1]; accumNormals[idx][2]+=normal[2];
            accumUV[idx][0]+=triUV[k][0]; accumUV[idx][1]+=triUV[k][1]; uvCount[idx]++;
        }
    }

    vector<Vec3> finalNormals(uniquePos.size());
    vector<Vec2> finalUVs(uniquePos.size());
    for (size_t i=0;i<uniquePos.size();i++){
        Vec3 n=accumNormals[i]; normalizeVec(n); finalNormals[i]=n;
        finalUVs[i]=(uvCount[i]>0)?Vec2{accumUV[i][0]/uvCount[i],accumUV[i][1]/uvCount[i]}:Vec2{0,0};
    }

    outFile << fixed << setprecision(6);
    for (size_t i=0;i<uniquePos.size();i++)
        outFile<<"v "<<uniquePos[i][0]<<' '<<uniquePos[i][1]<<' '<<uniquePos[i][2]<<'\n';
    for (size_t i=0;i<finalUVs.size();i++)
        outFile<<"vt "<<finalUVs[i][0]<<' '<<finalUVs[i][1]<<'\n';
    for (size_t i=0;i<finalNormals.size();i++)
        outFile<<"vn "<<finalNormals[i][0]<<' '<<finalNormals[i][1]<<' '<<finalNormals[i][2]<<'\n';

    for (size_t i=0;i+2<points.size();i+=3){
        int i0=posToIndex[makeKey(points[i])]+1;
        int i1=posToIndex[makeKey(points[i+1])]+1;
        int i2=posToIndex[makeKey(points[i+2])]+1;
        outFile<<"f "<<i0<<'/'<<i0<<'/'<<i0<<' '<<i1<<'/'<<i1<<'/'<<i1<<' '<<i2<<'/'<<i2<<'/'<<i2<<'\n';
    }
    outFile.close();
    cout << "Figure generated successfully: " << outputPath << endl;
    cout << "Total: " << vertices.size() << " vertices ("<<vertices.size()/3<<" triangles)" << endl;
}

static vector<string> loadModel(const string& modelFile) {
    string modelPath = "../../figures/" + modelFile;
    vector<string> lines = extractVertexLines(modelPath);
    if (lines.empty()) {
        string alt = modelPath;
        size_t dot = alt.find_last_of('.');
        if (dot != string::npos) {
            string ext = alt.substr(dot+1);
            if (ext == "3d") alt = alt.substr(0,dot)+".obj";
            else if (ext == "obj") alt = alt.substr(0,dot)+".3d";
        }
        if (alt != modelPath) lines = extractVertexLines(alt);
        if (lines.empty()) { cerr << "Error: Could not open model file " << modelPath << endl; return {}; }
    }
    return lines;
}

