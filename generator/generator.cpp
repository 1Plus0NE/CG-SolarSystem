int main(int argc, char* argv[]) {
    if (argc < 3) {
        cerr << "Usage: " << argv[0] << " <shape> <parameters...> <output_file>" << endl;
        cerr << "  sphere   <radius> <slices> <stacks> <out>" << endl;
        cerr << "  box      <length> <divisions> <out>" << endl;
        cerr << "  cone     <radius> <height> <slices> <stacks> <out>" << endl;
        cerr << "  plane    <length> <divisions> <out>" << endl;
        cerr << "  cylinder <radius> <height> <slices> <stacks> <out>" << endl;
        cerr << "  icosphere <radius> <subdivisions> <out>" << endl;
        cerr << "  torus    <R> <r> <slices> <stacks> <out>" << endl;
        cerr << "  ring     <innerR> <outerR> <slices> <out>" << endl;
        cerr << "  octahedron <scale> <out>" << endl;
        cerr << "  bezier   <patchfile> <tessellation> <out>" << endl;
        cerr << "  scatter  <volume_shape> <volume_params...> <num> <model.obj> <smin> <smax> <out>" << endl;
        return 1;
    }

    list<string> arglist;
    string figure = argv[1];
    string file   = argv[argc - 1];
    for (int i = 2; i < argc - 1; i++) arglist.push_back(argv[i]);

    // ── shapes that use the proper VertList path ─────────────────────────────
    VertList verts;

    if (figure == "sphere") {
        if (arglist.size() != 3) { cerr << "Usage: sphere <radius> <slices> <stacks> <out>" << endl; return 1; }
        float radius = stof(arglist.front()); arglist.pop_front();
        int slices   = stoi(arglist.front()); arglist.pop_front();
        int stacks   = stoi(arglist.front());
        if (!verifyMetric("radius",radius,0.01)||!verifyMetric("slices",slices,1)||!verifyMetric("stacks",stacks,1)) return 1;
        generateSphere(radius, slices, stacks, verts);
        writeOutput(verts, file);

    } else if (figure == "box") {
        if (arglist.size() != 2) { cerr << "Usage: box <length> <divisions> <out>" << endl; return 1; }
        float length    = stof(arglist.front()); arglist.pop_front();
        int   divisions = stoi(arglist.front());
        if (!verifyMetric("length",length,0.01)||!verifyMetric("divisions",divisions,1)) return 1;
        generateBox(length, divisions, verts);
        writeOutput(verts, file);

    } else if (figure == "cone") {
        if (arglist.size() != 4) { cerr << "Usage: cone <radius> <height> <slices> <stacks> <out>" << endl; return 1; }
        float radius = stof(arglist.front()); arglist.pop_front();
        float height = stof(arglist.front()); arglist.pop_front();
        int slices   = stoi(arglist.front()); arglist.pop_front();
        int stacks   = stoi(arglist.front());
        if (!verifyMetric("radius",radius,0.01)||!verifyMetric("height",height,0.01)||!verifyMetric("slices",slices,1)||!verifyMetric("stacks",stacks,1)) return 1;
        generateCone(radius, height, slices, stacks, verts);
        writeOutput(verts, file);

    } else if (figure == "plane") {
        if (arglist.size() != 2) { cerr << "Usage: plane <length> <divisions> <out>" << endl; return 1; }
        float length    = stof(arglist.front()); arglist.pop_front();
        int   divisions = stoi(arglist.front());
        if (!verifyMetric("length",length,0.01)||!verifyMetric("divisions",divisions,1)) return 1;
        generatePlane(length, divisions, verts);
        writeOutput(verts, file);

    } else if (figure == "cylinder") {
        if (arglist.size() != 4) { cerr << "Usage: cylinder <radius> <height> <slices> <stacks> <out>" << endl; return 1; }
        float radius = stof(arglist.front()); arglist.pop_front();
        float height = stof(arglist.front()); arglist.pop_front();
        int slices   = stoi(arglist.front()); arglist.pop_front();
        int stacks   = stoi(arglist.front());
        if (!verifyMetric("radius",radius,0.01)||!verifyMetric("height",height,0.01)||!verifyMetric("slices",slices,1)||!verifyMetric("stacks",stacks,1)) return 1;
        generateCylinder(radius, height, slices, stacks, verts);
        writeOutput(verts, file);

    } else if (figure == "icosphere") {
        if (arglist.size() != 2) { cerr << "Usage: icosphere <radius> <subdivisions> <out>" << endl; return 1; }
        float radius = stof(arglist.front()); arglist.pop_front();
        int   subs   = stoi(arglist.front());
        if (!verifyMetric("radius",radius,0.01)||!verifyMetric("subdivisions",subs,0)) return 1;
        generateIcosphere(radius, subs, verts);
        writeOutput(verts, file);

    } else if (figure == "torus") {
        if (arglist.size() != 4) { cerr << "Usage: torus <R> <r> <slices> <stacks> <out>" << endl; return 1; }
        float R = stof(arglist.front()); arglist.pop_front();
        float r = stof(arglist.front()); arglist.pop_front();
        int slices = stoi(arglist.front()); arglist.pop_front();
        int stacks = stoi(arglist.front());
        generateTorus(R, r, slices, stacks, verts);
        writeOutput(verts, file);

    } else if (figure == "ring") {
        if (arglist.size() != 3) { cerr << "Usage: ring <innerR> <outerR> <slices> <out>" << endl; return 1; }
        float innerR = stof(arglist.front()); arglist.pop_front();
        float outerR = stof(arglist.front()); arglist.pop_front();
        int   slices  = stoi(arglist.front());
        if (!verifyMetric("innerRadius",innerR,0.0f)||!verifyMetric("outerRadius",outerR,0.01f)||!verifyMetric("slices",slices,3)) return 1;
        generateRing(innerR, outerR, slices, verts);
        writeOutput(verts, file);

    } else if (figure == "octahedron") {
        if (arglist.size() != 1) { cerr << "Usage: octahedron <scale> <out>" << endl; return 1; }
        float scale = stof(arglist.front());
        if (!verifyMetric("scale", scale, 0.01f)) return 1;
        generateOctahedron(verts, 0.0f, 0.0f, 0.0f, scale);
        writeOutput(verts, file);

    } else if (figure == "bezier") {
        if (arglist.size() != 2) { cerr << "Usage: bezier <patchfile> <tessellation> <out>" << endl; return 1; }
        string patchFile = arglist.front(); arglist.pop_front();
        int tess = stoi(arglist.front());
        if (!verifyMetric("tessellation",tess,1)) return 1;
        generateBezier(patchFile, tess, verts);
        writeOutput(verts, file);

    // ── scatter — legacy list<string> path ───────────────────────────────────
    } else if (figure == "scatter") {
        if (arglist.empty()) { cerr << "scatter: missing volume shape" << endl; return 1; }
        string shape = arglist.front(); arglist.pop_front();

        int numParams = 0;
        if      (shape == "sphere")   numParams = 2;
        else if (shape == "torus")    numParams = 3;
        else if (shape == "plane")    numParams = 2;
        else if (shape == "cylinder") numParams = 4;
        else if (shape == "box")      numParams = 2;
        else { cerr << "scatter: unknown volume shape '" << shape << "'" << endl; return 1; }

        if ((int)arglist.size() < numParams + 4) {
            cerr << "scatter: not enough arguments for shape '" << shape << "'" << endl; return 1;
        }

        vector<float> params;
        for (int i = 0; i < numParams; i++) { params.push_back(stof(arglist.front())); arglist.pop_front(); }

        int    num       = stoi(arglist.front()); arglist.pop_front();
        string modelFile =      arglist.front();  arglist.pop_front();
        float  scaleMin  = stof(arglist.front()); arglist.pop_front();
        float  scaleMax  = stof(arglist.front()); arglist.pop_front();

        vector<string> modelVerts = loadModel(modelFile);
        if (modelVerts.empty()) return 1;

        srand(42);
        list<string> legacyVerts;
        for (int i = 0; i < num; i++) {
            ScatterSample pos;
            if (!sampleVolume(shape, params, pos)) return 1;
            float scale = scaleMin + rand01() * (scaleMax - scaleMin);
            float rx = rand01()*2.0f*M_PI, ry = rand01()*2.0f*M_PI, rz = rand01()*2.0f*M_PI;
            for (const string& v : modelVerts)
                legacyVerts.push_back(transformVertex(v, pos.x, pos.y, pos.z, rx, ry, rz, scale));
        }
        writeOutputLegacy(legacyVerts, file);

    } else {
        cerr << "Unknown figure type: " << figure << endl;
        return 1;
    }

    return 0;
}
