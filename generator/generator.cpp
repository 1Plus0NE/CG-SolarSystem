using Vec3 = array<float, 3>;
using Vec2 = array<float, 2>;

static Vec3 parseVec3(const string& line) {
    istringstream iss(line);
    Vec3 p{};
    iss >> p[0] >> p[1] >> p[2];
    return p;
}

static Vec3 subtractVec(const Vec3& a, const Vec3& b) {
    return {a[0]-b[0], a[1]-b[1], a[2]-b[2]};
}

static Vec3 crossVec(const Vec3& a, const Vec3& b) {
    return {a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0]};
}

static void normalizeVec(Vec3& v) {
    float len = sqrt(v[0]*v[0]+v[1]*v[1]+v[2]*v[2]);
    if (len > 1e-6f) { v[0]/=len; v[1]/=len; v[2]/=len; }
    else v = {0,0,1};
}

static Vec2 projectTexCoord(const Vec3& p, const Vec3& n) {
    float ax = fabs(n[0]), ay = fabs(n[1]), az = fabs(n[2]);
    if (ax >= ay && ax >= az) return {p[1], p[2]};
    if (ay >= ax && ay >= az) return {p[0], p[2]};
    return {p[0], p[1]};
}

static array<Vec2, 3> buildTriangleUVs(const Vec3& p0, const Vec3& p1, const Vec3& p2, const Vec3& n) {
    array<Vec2, 3> proj = {projectTexCoord(p0,n), projectTexCoord(p1,n), projectTexCoord(p2,n)};
    float minU=proj[0][0],maxU=proj[0][0],minV=proj[0][1],maxV=proj[0][1];
    for (int i=1;i<3;i++){minU=min(minU,proj[i][0]);maxU=max(maxU,proj[i][0]);minV=min(minV,proj[i][1]);maxV=max(maxV,proj[i][1]);}
    float du=maxU-minU, dv=maxV-minV;
    array<Vec2,3> uv={};
    for (int i=0;i<3;i++){uv[i][0]=(du>1e-6f)?((proj[i][0]-minU)/du):0;uv[i][1]=(dv>1e-6f)?((proj[i][1]-minV)/dv):0;}
    return uv;
}

static vector<string> extractVertexLines(const string& modelPath) {
    ifstream f(modelPath);
    if (!f.is_open()) return {};
    vector<string> lines;
    string line;
    bool first = true;
    while (getline(f, line)) {
        if (line.empty() || line[0] == '#') continue;
        istringstream iss(line);
        string tag; iss >> tag;
        if (tag == "v") {
            string x, y, z;
            if (iss >> x >> y >> z) lines.push_back(x+" "+y+" "+z);
            continue;
        }
        if (first) {
            first = false;
            bool num = !tag.empty() && (isdigit((unsigned char)tag[0]) || tag[0]=='-' || tag[0]=='+');
            if (num) continue;
        }
    }
    if (lines.empty()) {
        f.clear(); f.seekg(0); first=true;
        while (getline(f,line)){if(first){first=false;continue;}if(!line.empty())lines.push_back(line);}
    }
    return lines;
}

